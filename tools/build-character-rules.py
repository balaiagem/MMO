"""Compile pinned SRD class/race progression into the server's Lua module."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0,str(ROOT))
from rules.catalog2014 import collection,class_level
CLASS_IDS=['fighter','rogue','cleric','wizard','barbarian','bard','druid','monk','paladin','ranger','sorcerer','warlock']
RACE_IDS=['human','elf','dwarf','halfling','dragonborn','gnome','half-elf','half-orc','tiefling']
SUBRACES={'dwarf':'hill-dwarf','elf':'high-elf','halfling':'lightfoot-halfling','gnome':'rock-gnome'}
def lua(value):
    if value is None:return 'nil'
    if isinstance(value,bool):return 'true' if value else 'false'
    if isinstance(value,str):return json.dumps(value,ensure_ascii=True)
    if isinstance(value,(int,float)):return str(value)
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
def main():
    classes={};races={}
    for number,index in enumerate(CLASS_IDS,1):
        source=collection('Classes')[index]
        levels={}
        for level in range(1,6):
            row=class_level(index,level)
            levels[level]={'features':[f['index'] for f in row['features']], 'specific':row.get('class_specific',{}),'magic':row.get('spellcasting',{})}
        sub=source['subclasses'][0]['index']
        sublevels={row['level']:[f['index'] for f in row['features']] for row in collection('Levels').values() if row.get('subclass',{}).get('index')==sub and row['level']<=5}
        classes[number]={'index':index,'hitDie':source['hit_die'],'saves':[s['index'].upper() for s in source['saving_throws']], 'spellAbility':source.get('spellcasting',{}).get('spellcasting_ability',{}).get('index','').upper(),'subclass':sub,'levels':levels,'subclassLevels':sublevels}
    for number,index in enumerate(RACE_IDS,1):
        source=collection('Races')[index];bonuses={};traits=[t['index'] for t in source['traits']]
        for bonus in source['ability_bonuses']:bonuses[bonus['ability_score']['index'].upper()]=bonus['bonus']
        sub=SUBRACES.get(index)
        if sub:
            row=collection('Subraces')[sub]
            for bonus in row['ability_bonuses']:
                ability=bonus['ability_score']['index'].upper();bonuses[ability]=bonuses.get(ability,0)+bonus['bonus']
            traits.extend(t['index'] for t in row.get('racial_traits',[]))
        races[number]={'index':index,'speed':source['speed'],'bonuses':bonuses,'traits':traits,'subrace':sub}
    target=ROOT/'rules/character_data.lua'
    target.write_text('-- Generated by tools/build-character-rules.py from the pinned SRD 2014 collections.\nreturn '+lua({'classes':classes,'races':races})+'\n',encoding='utf-8')
    print('Compiled 12 stable class IDs, 9 race IDs and 60 class-level records.')
if __name__=='__main__':main()
