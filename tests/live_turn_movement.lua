-- Temporary startup probe for the isolated local runtime. Creates/removes its own Rat.
local test=GlobalEvent('VerifyTurnMovement')
test:type('startup')
test:onStartup(function()
    local rat=Game.createMonster('Rat',Position(114,114,7),false,true)
    assert(rat,'could not create isolated movement fixture')
    local ok,err=pcall(function()
        rat:setTurnMovement(0);rat:move(DIRECTION_EAST)
        assert(rat:getPosition().x==114,'inactive actor moved')
        rat:setTurnMovement(500);rat:move(DIRECTION_EAST)
        assert(rat:getPosition().x==115 and rat:getTurnMovement()==0,'cardinal cost incorrect')
        rat:move(DIRECTION_EAST);assert(rat:getPosition().x==115,'exhausted actor moved')
        rat:setTurnMovement(707);rat:move(DIRECTION_NORTHEAST)
        assert(rat:getPosition().x==116 and rat:getPosition().y==113 and rat:getTurnMovement()==0,'diagonal cost incorrect')
        rat:setTurnMovement(-1);rat:move(DIRECTION_EAST)
        assert(rat:getPosition().x==117 and rat:getTurnMovement()==-1,'exploration was not restored')
    end)
    rat:remove()
    assert(ok,err)
    print('[TEST] Native turn movement: inactive, exhausted, cardinal, diagonal and exploration PASS')
    return true
end)
test:register()
